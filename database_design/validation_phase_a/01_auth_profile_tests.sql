  GET STACKED DIAGNOSTICS got=RETURNED_SQLSTATE;
  IF got<>wanted THEN RAISE EXCEPTION '% expected %, got %',label,wanted,got; END IF;
  INSERT INTO test_a.results VALUES(label,true); RETURN;
 END;
 RAISE EXCEPTION '% unexpectedly succeeded',label;
END $$;
