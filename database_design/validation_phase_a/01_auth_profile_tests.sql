CREATE FUNCTION test_a.ok(label text,value boolean) RETURNS void LANGUAGE plpgsql AS $$ BEGIN
 IF value IS DISTINCT FROM true THEN RAISE EXCEPTION 'Assertion failed: %',label; END IF;
 INSERT INTO test_a.results VALUES(label,true);
END $$;
CREATE FUNCTION test_a.deny(label text,statement text,wanted text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE got text;
BEGIN
 BEGIN EXECUTE statement;
